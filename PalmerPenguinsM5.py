# Using loops to repeatedly explore Palmer Penguins statistics.

#Constants representing the names and total of species
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"

NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151

species_names = [
    SP_CHINSTRAP,
    SP_GENTOO,
    SP_ADELIE
]

species_counts = [
    NUM_CHINSTRAP,
    NUM_GENTOO,
    NUM_ADELIE
]

#Calculating the number of penguin species
total_species = len(species_names)

#Calculating the toltal number of penguins.
total_penguins = sum(species_counts)

#Calculating the average number of penguins per species.
average_penguins = total_penguins /total_species
average_penguins_rounded_up = math.ceil(average_penguins)

#Calculating the species percentage using list indexes.
chinstrap_percent = (species_counts[0] / total_penguins) * 100
gentoo_percent = (species_counts[1] / total_penguins) * 100
adelie_percent = (species_counts[2] / total_penguins) * 100

#Module 4_Creating a list of species percentages
species_percentages = [chinstrap_percent, gentoo_percent, adelie_percent]

##Calculating the species with the most and fewest oberservations.
largest_count = max(species_counts)
smallest_count = min(species_counts)


largest_index = species_counts.index(largest_count)
smallest_index = species_counts.index(smallest_count)

largest_species = species_names[largest_index]
smallest_species = species_names[smallest_index]

#Output the names with introduction text
print("Introducing the Palmer Penguins:")
print("\t" + SP_CHINSTRAP + "!")
print("\t" + SP_GENTOO + "!")
print("and last but not least...")
print("\t" + SP_ADELIE + "!")
print()

#Output of calcutions.
print(f"There are a total of {total_species} penguin species in this dataset.")
print(f"There are a total of {total_penguins} penguin in this dataset.")
print(f"The average number of penguins per species is {average_penguins}.")
print(f"The average rounded up is {average_penguins_rounded_up} penguins.")
print()
print("Chinstrap:", NUM_CHINSTRAP, f"({chinstrap_percent:.2f}%)")
print("Gentoo:", NUM_GENTOO, f"({gentoo_percent:.2f}%)")
print("Adelie:", NUM_ADELIE, f"({adelie_percent:.2f}%)")
print()
print("The species with the most observations is " +
      largest_species + " with " + str(largest_count) + " penguins.")
print("The species with the fewest observations is " +
      smallest_species + " with " + str(smallest_count) + " penguins.")
print()

#Module 5_Counter for Valid Species Selections
valid_selections = 0

#Module 4_Adding an interactive Species Selection Section
print("Explore a species:")

#Prompt the user to select a species

species_choice = input("Enter Chinstrap, Gentoo, Adelie, or Done: ")
print()

#Module 5_Using a for loop to display species statistics
while species_choice != "Done":
    for index, species in enumerate(species_names):
        if species_choice == species:
            valid_selections += 1

            print()
            print(str(species_names[index]) + " has " + str(species_counts[index]) + " observations,""" +
                  " representing " + str(f"{species_percentages[index]:.2f}%") + " of the dataset.")

            #Classify the selected species
            if species_percentages[index] < 25:
                category = "small"
            elif (species_percentages[index] >= 25) and (species_percentages[index] < 40):
                category = "medium"
            else:
                category = "large"

            #Determine the species relative size
            if (species_names[index] == largest_species):
                size = "largest"
            elif (species_names[index] == smallest_species):
                size = "smallest"
            else:
                size = "middle-sized"

            #Compare selected species to average.
            if (species_counts[index] > average_penguins_rounded_up):
                position = "above"
            else:
                position = "below"

            #Output selected species statistics.
            print((species_names[index]) + " is classified as a " + category + " species group.")
            print(str(species_names[index]) + " is the " + size + " species group.")
            print("Its observation count is", position, "the dataset avergae of", average_penguins)

    #If input is not valid
    if species_choice not in species_names:
        print()
        print("***", species_choice, "is not one of the species in this dataset.", "***")

    print()
    species_choice = input("Enter Chinstrap, Gentoo, Adelie, or Done: ")

#Exploration summary
print()
print("You explored", valid_selections, "valid species.")
print("Exploration complete.")